#!/usr/bin/env python3
"""Extracts Audacity's built-in factory presets from the C++ sources in ../au3 into
crates/au-effects/src/factory_presets.rs (Compressor, Limiter, Distortion)."""
import re, os
R = os.path.realpath(os.path.join(os.path.dirname(__file__), ".."))
AU3 = os.path.join(R, "..", "au3", "libraries")
out = []
h = open(f"{AU3}/au3-dynamic-range-processor/DynamicRangeProcessorUtils.h").read()
for var, eid in (("serializedCompressorPresets", "Compressor"), ("serializedLimiterPresets", "Limiter")):
    body = h[h.index(var):]; body = body[:body.index("};")]
    for name, s in re.findall(r'TranslatableString\("[^"]*", "([^"]+)"\),\s*"(?:\w+):((?:[^"\\]|\\.)*)"', body):
        out.append((eid, name, s.replace('\\"', '"')))
d = open(f"{AU3}/au3-builtin-effects/DistortionBase.cpp").read()
types = ["Hard Clipping", "Soft Clipping", "Soft Overdrive", "Medium Overdrive", "Hard Overdrive", "Cubic Curve (odd harmonics)",
         "Even Harmonics", "Expand and Compress", "Leveller", "Rectifier Distortion", "Hard Limiter 1413"]
for name, vals in re.findall(r'TranslatableString\("builtin-effects", "([^"]+)"\),\s*\{([^}]*)\}', d):
    v = [x.strip() for x in vals.split(",")]
    p = (f'Type="{types[int(v[0])]}" DC Block="{v[1]}" Threshold dB="{v[2]}" Noise Floor="{v[3]}" '
         f'Parameter 1="{v[4]}" Parameter 2="{v[5]}" Repeats="{v[6]}"')
    out.append(("Distortion", name, p))
with open(f"{R}/crates/au-effects/src/factory_presets.rs", "w") as f:
    f.write("// @generated by tools/gen_factory_presets.py from Audacity's C++ sources. GPL-3.0-or-later.\n")
    f.write("//! Factory preset tables (effect id, preset name, Audacity parameter string).\n")
    f.write("/// `(effect id, preset name, parameters)`.\npub static FACTORY: &[(&str, &str, &str)] = &[\n")
    for e, n, s in out: f.write(f"    ({e!r}, {n!r}, {s!r}),\n".replace("'", '"') if '"' not in s else f"    (\"{e}\", \"{n}\", r#\"{s}\"#),\n")
    f.write("];\n")
print(len(out), "presets")
